const STORAGE_KEY = 'opp_lang'

export function getStoredLanguage() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (raw && LANGUAGES.some((l) => l.code === raw)) return raw
  } catch {
    /* ignore */
  }
  return null
}

export function storeLanguage(code) {
  try {
    localStorage.setItem(STORAGE_KEY, code)
  } catch {
    /* ignore */
  }
}

export function detectBrowserLanguage() {
  if (typeof navigator === 'undefined') return 'en'
  const candidates = [...(navigator.languages || []), navigator.language || 'en']
  for (const raw of candidates) {
    if (!raw) continue
    const lower = raw.toLowerCase()
    const exact = LANGUAGES.find((l) => l.code.toLowerCase() === lower)
    if (exact) return exact.code
    const base = lower.split('-')[0]
    const baseMatch = LANGUAGES.find((l) => l.code.toLowerCase() === base)
    if (baseMatch) return baseMatch.code
    // pt-BR style
    const regional = LANGUAGES.find((l) => l.code.toLowerCase().startsWith(`${base}-`))
    if (regional && lower.startsWith(base)) return regional.code
  }
  return 'en'
}

export function nativeLanguageName(code, displayLocale = code) {
  try {
    const dn = new Intl.DisplayNames([displayLocale], { type: 'language' })
    const name = dn.of(code.includes('-') ? code : code)
    if (name && name !== code) return name
  } catch {
    /* ignore */
  }
  return LANGUAGES.find((l) => l.code === code)?.name || code
}

export function languageMeta(code) {
  return LANGUAGES.find((l) => l.code === code) || { code, name: code }
}
